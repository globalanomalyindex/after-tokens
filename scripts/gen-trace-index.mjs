// Generates lib/traces/index.ts: a static map of trace id -> lazy JSON import.
// Static so every bundler can code-split it; lazy so the page only downloads
// the trajectories a visitor actually opens.
import { readdirSync, writeFileSync, readFileSync } from 'node:fs'
const dir = new URL('../data/traces/compact/', import.meta.url)
const files = readdirSync(dir).filter((f) => f.endsWith('.json')).sort()

// LOOP_RULE. A small model decoded greedily can fall into a repetition loop
// and spend most of its answer repeating one phrase. The trajectory is still
// a real trajectory (order, confidence, and timing are all measured and it
// stays in every statistic), but the page marks it so a reader knows what
// they are watching. A run is flagged when one 2- to 8-word phrase repeats
// back to back at least three times and those repeats cover at least 30% of
// the words. On the recorded set this separates cleanly: three default-
// sampler runs at 77% to 88% coverage, every other run at 0%.
const LOOP_MIN_REPS = 3
const LOOP_MIN_COVER = 0.3
function detectLoop(words) {
  const n = words.length
  let best = null
  for (let g = 2; g <= 8; g++) {
    for (let i = 0; i + 2 * g <= n; i++) {
      const unit = words.slice(i, i + g).join(' ')
      let reps = 1
      while (i + (reps + 1) * g <= n && words.slice(i + reps * g, i + (reps + 1) * g).join(' ') === unit) reps++
      if (reps >= LOOP_MIN_REPS && (!best || reps * g > best.span)) best = { phrase: unit, reps, span: reps * g }
    }
  }
  if (!best || n === 0 || best.span / n < LOOP_MIN_COVER) return null
  return { phrase: best.phrase, reps: best.reps, cover: Number((best.span / n).toFixed(2)) }
}

// AUDIT_RULE. Every recorded answer gets one verdict, so the page can say
// what a reader is watching and the product demos can decide what to show:
//   empty    no content token committed (the sampler committed its
//            end-of-sequence tokens first, a known cost of removing the
//            schedule)
//   short    under MIN_CONTENT content tokens, the floor the order
//            statistics use (two tokens are always in order)
//   looped   LOOP_RULE above
//   cut      the answer used every position and did not end on its own
//            end-of-sequence token, or does not end in terminal punctuation
//   complete none of the above: the model chose its own ending
const MIN_CONTENT = 8
function audit(j, loop) {
  const content = j.tokens.filter((t) => !t.tail).length
  const tail = j.tokens.length - content
  const answer = j.answer.trim()
  const endsWell = /[.!?…"”)]$/.test(answer)
  if (content === 0) return { verdict: 'empty', note: 'no content token committed; the sampler committed its end-of-sequence tokens first' }
  if (content < MIN_CONTENT) return { verdict: 'short', note: `${content} content tokens, under the ${MIN_CONTENT}-token floor the order statistics use` }
  if (loop) return { verdict: 'looped', note: `one phrase repeated ${loop.reps} times over ${Math.round(loop.cover * 100)}% of the answer` }
  if (tail === 0 || !endsWell) return { verdict: 'cut', note: 'the answer ran to the position limit without an ending of its own' }
  return { verdict: 'complete', note: 'the model chose its own ending' }
}

const entries = files.map((f) => {
  const id = f.replace(/\.json$/, '')
  const j = JSON.parse(readFileSync(new URL(f, dir), 'utf8'))
  const loop = detectLoop(j.words.map((w) => w.text))
  return {
    id,
    prompt_id: j.prompt_id,
    config: j.sampler.id,
    words: j.words.length,
    loop,
    audit: audit(j, loop),
  }
})
const metaLine = (e) => {
  const loop = e.loop
    ? `, loop: { phrase: ${JSON.stringify(e.loop.phrase)}, reps: ${e.loop.reps}, cover: ${e.loop.cover} }`
    : ''
  return `  '${e.id}': { promptId: '${e.prompt_id}', config: '${e.config}', words: ${e.words}, audit: { verdict: '${e.audit.verdict}', note: ${JSON.stringify(e.audit.note)} }${loop} },`
}
const out = `// GENERATED by scripts/gen-trace-index.mjs. Do not edit by hand.
import { asTrace, type TraceCompact } from '@/lib/diffusion/traces'

export type TraceId = ${entries.map((e) => `'${e.id}'`).join(' | ')}

export const TRACE_IDS: readonly TraceId[] = [
${entries.map((e) => `  '${e.id}',`).join('\n')}
] as const

/** A repetition loop the model fell into: the phrase, how many times it
 *  repeated back to back, and the share of the answer's words it covers.
 *  Present only on runs that meet LOOP_RULE in scripts/gen-trace-index.mjs. */
export type TraceLoop = { phrase: string; reps: number; cover: number }

/** One verdict per recorded answer (AUDIT_RULE in scripts/gen-trace-index.mjs). */
export type TraceVerdict = 'complete' | 'looped' | 'short' | 'empty' | 'cut'
export type TraceAudit = { verdict: TraceVerdict; note: string }

// Lightweight metadata available without loading a trajectory.
export const TRACE_META: Record<TraceId, { promptId: string; config: string; words: number; audit: TraceAudit; loop?: TraceLoop }> = {
${entries.map(metaLine).join('\n')}
}

const loaders: Record<TraceId, () => Promise<TraceCompact>> = {
${entries.map((e) => `  '${e.id}': () => import('@/data/traces/compact/${e.id}.json').then((m) => asTrace(m.default)),`).join('\n')}
}

export function loadTrace(id: TraceId): Promise<TraceCompact> {
  return loaders[id]()
}
`
writeFileSync(new URL('../lib/traces/index.ts', import.meta.url), out)
const tally = {}
for (const e of entries) {
  tally[e.config] ??= {}
  tally[e.config][e.audit.verdict] = (tally[e.config][e.audit.verdict] ?? 0) + 1
}
console.log(`wrote lib/traces/index.ts with ${entries.length} traces; audit: ${JSON.stringify(tally)}`)
