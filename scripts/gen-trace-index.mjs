// Generates lib/traces/index.ts: a static map of trace id -> lazy JSON import.
// Static so every bundler can code-split it; lazy so the page only downloads
// the trajectories a visitor actually opens.
import { readdirSync, writeFileSync, readFileSync } from 'node:fs'
const dir = new URL('../data/traces/compact/', import.meta.url)
const files = readdirSync(dir).filter((f) => f.endsWith('.json')).sort()
const entries = files.map((f) => {
  const id = f.replace(/\.json$/, '')
  const j = JSON.parse(readFileSync(new URL(f, dir), 'utf8'))
  return { id, prompt_id: j.prompt_id, config: j.sampler.id, words: j.words.length, answer: j.answer }
})
const out = `// GENERATED by scripts/gen-trace-index.mjs. Do not edit by hand.
import { asTrace, type TraceCompact } from '@/lib/diffusion/traces'

export type TraceId = ${entries.map((e) => `'${e.id}'`).join(' | ')}

export const TRACE_IDS: readonly TraceId[] = [
${entries.map((e) => `  '${e.id}',`).join('\n')}
] as const

// Lightweight metadata available without loading a trajectory.
export const TRACE_META: Record<TraceId, { promptId: string; config: string; words: number }> = {
${entries.map((e) => `  '${e.id}': { promptId: '${e.prompt_id}', config: '${e.config}', words: ${e.words} },`).join('\n')}
}

const loaders: Record<TraceId, () => Promise<TraceCompact>> = {
${entries.map((e) => `  '${e.id}': () => import('@/data/traces/compact/${e.id}.json').then((m) => asTrace(m.default)),`).join('\n')}
}

export function loadTrace(id: TraceId): Promise<TraceCompact> {
  return loaders[id]()
}
`
writeFileSync(new URL('../lib/traces/index.ts', import.meta.url), out)
console.log(`wrote lib/traces/index.ts with ${entries.length} traces`)
